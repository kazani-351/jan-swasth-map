#!/usr/bin/env python3
"""T2 — Ingest EpiClim -> normalized district-week store -> db/seed.sql.

Snapshot pipeline: reads the committed raw EpiClim CSV, filters to the 3 pilot states and
3 target diseases, aggregates duplicate same-date reports, and emits idempotent SQL.
Fail-loud: any missing input or an empty pilot state exits non-zero (never a silent success).
Self-verifies by loading schema + seed into an in-memory SQLite (D1 is SQLite) and asserting.

Run:  python3 pipeline/ingest.py     (from repo root)
"""
import csv, os, re, sqlite3, sys, datetime
from collections import defaultdict

RAW = "data/raw/Final_data.csv"
SCHEMA = "db/schema.sql"
OUT = "db/seed.sql"
SOURCE = "IDSP via EpiClim (Zenodo 14580510)"

PILOT = {"Maharashtra": "mh", "Tamil Nadu": "tn", "West Bengal": "wb"}
DISEASES = {"Dengue", "Malaria", "Acute Diarrhoeal Disease"}


def die(msg):
    print(f"FATAL: {msg}", file=sys.stderr)
    sys.exit(1)


def slug(s):
    return re.sub(r"_+", "_", re.sub(r"[^a-z0-9]+", "_", s.strip().lower())).strip("_")


def q(v):  # SQL literal
    if v is None or v == "":
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def main():
    if not os.path.exists(RAW):
        die(f"raw data not found at {RAW} (run the download step first)")

    districts = {}                       # id -> {name, state, lats[], lons[]}
    obs = defaultdict(lambda: [0, 0, False])   # (id,disease,date) -> [cases, deaths, any_death]
    clim = {}                            # (id,date) -> [year, month, precip, temp, lai]
    n_in = n_kept = n_baddate = 0

    with open(RAW, newline="") as f:
        for r in csv.DictReader(f):
            n_in += 1
            state, dis = r["state_ut"], r["Disease"]
            if state not in PILOT or dis not in DISEASES:
                continue
            try:
                y, m, d = int(float(r["year"])), int(float(r["mon"])), int(float(r["day"]))
                date = datetime.date(y, m, d).isoformat()
            except (ValueError, KeyError):
                n_baddate += 1
                continue
            try:
                cases = int(float(r["Cases"])) if r["Cases"] else 0
            except ValueError:
                cases = 0
            did = f"{PILOT[state]}_{slug(r['district'])}"
            dr = districts.setdefault(did, {"name": r["district"], "state": state, "lat": [], "lon": []})
            for col, key in (("Latitude", "lat"), ("Longitude", "lon")):
                try:
                    dr[key].append(float(r[col]))
                except (ValueError, KeyError, TypeError):
                    pass
            rec = obs[(did, dis, date)]
            rec[0] += cases
            if r.get("Deaths"):
                try:
                    rec[1] += int(float(r["Deaths"])); rec[2] = True
                except ValueError:
                    pass
            def fnum(col):
                try:
                    return float(r[col])
                except (ValueError, KeyError, TypeError):
                    return None
            clim.setdefault((did, date), [y, m, fnum("preci"), fnum("Temp"), fnum("LAI")])
            n_kept += 1

    if not obs:
        die("zero observations after filtering — check pilot states / disease names")
    per_state = defaultdict(int)
    for (did, _, _) in obs:
        per_state[did.split("_", 1)[0]] += 1
    for abbr in PILOT.values():
        if per_state[abbr] == 0:
            die(f"pilot state '{abbr}' has zero observations — refusing to emit a partial snapshot")

    # emit seed.sql
    def mean(xs):
        return round(sum(xs) / len(xs), 6) if xs else None
    lines = ["-- generated by pipeline/ingest.py — do not edit by hand", "BEGIN;"]
    for did, dr in sorted(districts.items()):
        lines.append(
            f"INSERT OR IGNORE INTO districts (district_id,name,state,lat,lon) VALUES "
            f"({q(did)},{q(dr['name'])},{q(dr['state'])},{q(mean(dr['lat']))},{q(mean(dr['lon']))});")
    for (did, dis, date), (cases, deaths, anyd) in sorted(obs.items()):
        y, m = int(date[:4]), int(date[5:7])
        lines.append(
            f"INSERT OR REPLACE INTO observations (district_id,disease,obs_date,year,month,cases,deaths,source) "
            f"VALUES ({q(did)},{q(dis)},{q(date)},{y},{m},{cases},{q(deaths if anyd else None)},{q(SOURCE)});")
    for (did, date), (y, m, p, t, l) in sorted(clim.items()):
        lines.append(
            f"INSERT OR REPLACE INTO climate (district_id,obs_date,year,month,precip,temp_k,lai) "
            f"VALUES ({q(did)},{q(date)},{y},{m},{q(p)},{q(t)},{q(l)});")
    lines.append("COMMIT;")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")

    print(f"rows read={n_in}  kept={n_kept}  bad-date-skipped={n_baddate}")
    print(f"districts={len(districts)}  observations={len(obs)}  climate={len(clim)}")
    print(f"per-state obs: " + "  ".join(f"{k}={v}" for k, v in sorted(per_state.items())))
    print(f"wrote {OUT}")

    verify()


def verify():
    """Load schema + seed into in-memory SQLite; assert integrity. Fail-loud."""
    con = sqlite3.connect(":memory:")
    con.executescript(open(SCHEMA).read())
    con.executescript(open(OUT).read())
    cur = con.cursor()
    nd = cur.execute("SELECT COUNT(*) FROM districts").fetchone()[0]
    no = cur.execute("SELECT COUNT(*) FROM observations").fetchone()[0]
    nc = cur.execute("SELECT COUNT(*) FROM climate").fetchone()[0]
    orphans = cur.execute(
        "SELECT COUNT(*) FROM observations o LEFT JOIN districts d USING(district_id) "
        "WHERE d.district_id IS NULL").fetchone()[0]
    neg = cur.execute("SELECT COUNT(*) FROM observations WHERE cases < 0").fetchone()[0]
    assert nd > 0 and no > 0 and nc > 0, "empty table after load"
    assert orphans == 0, f"{orphans} observations reference a missing district"
    assert neg == 0, f"{neg} negative case counts"
    print("\n[verify] loaded into SQLite OK  "
          f"districts={nd} observations={no} climate={nc} orphans={orphans}")
    print("[verify] top dengue districts (all years):")
    for row in cur.execute(
        "SELECT district_id, SUM(cases) c FROM observations WHERE disease='Dengue' "
        "GROUP BY district_id ORDER BY c DESC LIMIT 5"):
        print(f"    {row[0]:26s} {row[1]}")
    con.close()
    print("[verify] PASS")


if __name__ == "__main__":
    main()
